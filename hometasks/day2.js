"use strict";

function createTestLogger(testName) {
  const startTime = Date.now(); // Время старта теста
  let stepCount = 1;            // Счетчик шагов (скрытый внутри замыкания)

  // ВЕРНИТЕ функцию, которая принимает сообщение шага (например, "Клик по кнопке")
  // И выводит лог в консоль, увеличивая шаг на 1.
  return function(stepMessage) {
    const elapsed = Date.now() - startTime;
    console.log(`[Тест: ${testName}] [Шаг ${stepCount}] [+${elapsed}мс] -> ${stepMessage}`);
    stepCount++;
  };
}

// === ПРОВЕРКА РАБОТЫ ===

// Создаем независимый логгер для Теста Авторизации
const logAuthTest = createTestLogger("Авторизация");

logAuthTest("Открытие страницы логина"); 
// Должно вывести примерно: [Тест: Авторизация] [Шаг 1] [+0мс] -> Открытие страницы логина

setTimeout(() => {
  logAuthTest("Ввод логина и пароля");
  // Должно вывести примерно: [Тест: Авторизация] [Шаг 2] [+100мс] -> Ввод логина и пароля
}, 100);

setTimeout(() => {
  logAuthTest("Нажатие кнопки Войти");
  // Должно вывести примерно: [Тест: Авторизация] [Шаг 3] [+250мс] -> Нажатие кнопки Войти
}, 250);

// Имитируем параллельный запуск другого теста!
// Его счетчик шагов и время должны быть полностью изолированы.
setTimeout(() => {
  const logCartTest = createTestLogger("Корзина");
  logCartTest("Добавление товара в корзину");
  // Должно вывести: [Тест: Корзина] [Шаг 1] [+0мс] -> Добавление товара в корзину
}, 150);